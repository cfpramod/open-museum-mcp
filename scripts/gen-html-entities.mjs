// Generates src/htmlEntities.ts from the WHATWG named character reference table.
//
//   node scripts/gen-html-entities.mjs           rewrite src/htmlEntities.ts
//   node scripts/gen-html-entities.mjs --check   exit 1 if src/htmlEntities.ts is stale
//
// The input is scripts/data/whatwg-entities.json, a verbatim copy of
// https://html.spec.whatwg.org/entities.json. To refresh it, download that file over the copy, then run this
// script; the recorded sha256 changes with it and tests/htmlEntities.test.ts fails until the output is
// regenerated. No network access happens here, so the test runs offline.
//
// The output keys are the names exactly as the table writes them, without the leading '&': 'amp;' and
// the legacy 'amp' (the 106 names HTML decodes without a final ';').

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE_URL = 'https://html.spec.whatwg.org/entities.json';

const here = new URL('.', import.meta.url);
const inputPath = fileURLToPath(new URL('data/whatwg-entities.json', here));
const outputPath = fileURLToPath(new URL('../src/htmlEntities.ts', here));

export function generate(inputBytes) {
  const sha256 = createHash('sha256').update(inputBytes).digest('hex');
  const table = JSON.parse(inputBytes.toString('utf8'));
  const names = Object.keys(table).sort();
  const lines = names.map((key) => {
    if (!key.startsWith('&')) throw new Error(`unexpected key ${JSON.stringify(key)}`);
    const characters = table[key].characters;
    if (typeof characters !== 'string') throw new Error(`no characters for ${key}`);
    return `  ${JSON.stringify(key.slice(1))}: ${JSON.stringify(characters)},`;
  });
  const longest = Math.max(...names.map((k) => k.length - 1));
  return [
    '// GENERATED by scripts/gen-html-entities.mjs. Do not edit by hand.',
    `// Source: ${SOURCE_URL}`,
    '// Input: scripts/data/whatwg-entities.json (a verbatim copy of the source)',
    `// sha256 of the input: ${sha256}`,
    `// Names: ${names.length}, of which ${names.filter((k) => !k.endsWith(';')).length} are legacy names without a final ';'.`,
    '',
    '/** The HTML named character reference table: name (without the leading "&") to the characters it stands for. */',
    'export const HTML_NAMED_REFERENCES: Readonly<Record<string, string>> = {',
    ...lines,
    '};',
    '',
    '/** The length of the longest name in the table, ending ";" included. */',
    `export const HTML_NAMED_REFERENCE_MAX_LENGTH = ${longest};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate(readFileSync(inputPath));
  if (process.argv.includes('--check')) {
    const current = readFileSync(outputPath, 'utf8');
    if (current !== next) {
      console.error('src/htmlEntities.ts is stale: run node scripts/gen-html-entities.mjs');
      process.exit(1);
    }
    console.error('src/htmlEntities.ts is up to date');
  } else {
    writeFileSync(outputPath, next);
    console.error(`wrote ${outputPath}`);
  }
}
